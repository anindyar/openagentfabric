// composeFile is the subset of the Compose specification OAF renders. Field
// order here is the order in the output; map keys are sorted by the encoder,
// so rendering is deterministic.
type composeFile struct {
	Services map[string]*service          `yaml:"services"`
	Volumes  map[string]map[string]string `yaml:"volumes,omitempty"`
}

type service struct {
	Image           string                `yaml:"image"`
	Restart         string                `yaml:"restart,omitempty"`
	User            string                `yaml:"user,omitempty"`
	NetworkMode     string                `yaml:"network_mode,omitempty"`
	PID             string                `yaml:"pid,omitempty"`
	IPC             string                `yaml:"ipc,omitempty"`
	GPUs            string                `yaml:"gpus,omitempty"`
	ShmSize         string                `yaml:"shm_size,omitempty"`
	Devices         []string              `yaml:"devices,omitempty"`
	Ulimits         map[string]int        `yaml:"ulimits,omitempty"`
	SecurityOpt     []string              `yaml:"security_opt,omitempty"`
	Command         []string              `yaml:"command,omitempty"`
	Environment     map[string]string     `yaml:"environment,omitempty"`
	Ports           []string              `yaml:"ports,omitempty"`
	Volumes         []string              `yaml:"volumes,omitempty"`
	DependsOn       map[string]dependency `yaml:"depends_on,omitempty"`
	Healthcheck     *healthcheck          `yaml:"healthcheck,omitempty"`
	StopGracePeriod string                `yaml:"stop_grace_period,omitempty"`
	MemLimit        string                `yaml:"mem_limit,omitempty"`
	MemswapLimit    string                `yaml:"memswap_limit,omitempty"`
	Logging         *logging              `yaml:"logging,omitempty"`
}

type dependency struct {
	Condition string `yaml:"condition"`
}

type healthcheck struct {
	Test        []string `yaml:"test"`
	Interval    string   `yaml:"interval,omitempty"`
	Timeout     string   `yaml:"timeout,omitempty"`
	Retries     int      `yaml:"retries,omitempty"`
	StartPeriod string   `yaml:"start_period,omitempty"`
}

type logging struct {
	Driver  string            `yaml:"driver"`
	Options map[string]string `yaml:"options,omitempty"`
}

// newService applies the defaults every OAF container gets: restart after
// reboots and bounded logs, so a chatty container cannot fill the disk.
func newService(image string) *service {
	return &service{
		Image:   image,
		Restart: "unless-stopped",
		Logging: &logging{Driver: "json-file", Options: map[string]string{"max-size": "50m", "max-file": "3"}},
	}
}

// memoryLimitsMiB caps every stack container. GB10 memory is unified, so
// the stack lives in what the models leave free. Without a cgroup limit, a
// runaway container would drive the kernel's OOM killer toward the largest
// process, which is a vLLM; with one, only that container is killed and
// restarted. vLLM is sized by --gpu-memory-utilization instead and has no
// entry. The sum stays under 8 GiB (TestMemoryLimits).
var memoryLimitsMiB = map[string]int{
	// Measured idle on a DGX Spark, 2026-10-18: web 645, worker 548,
	// grafana 258, clickhouse 238, seaweedfs 93, postgres 86, prometheus
	// 43, node-exporter 14, valkey 12, agentgateway 12 (MiB).
	"langfuse-web":    2048, // Node heap 75% of this (nodeHeap)
	"langfuse-worker": 1024,
	"clickhouse":      1536, // ClickHouse sizes its caches to 90% of this
	"prometheus":      768,
	"grafana":         512,
	"postgres":        512,
	"seaweedfs":       384,
	"valkey":          256,
	"agentgateway":    256,
	"node-exporter":   64,
}

// valkeyMaxMemoryMiB keeps Valkey's data under its container limit: with
// noeviction, writes fail cleanly instead of the container being killed.
const valkeyMaxMemoryMiB = 192

func limitMemory(services map[string]*service) {
	for name, s := range services {
		if mib, ok := memoryLimitsMiB[name]; ok {
			s.MemLimit = fmt.Sprintf("%dm", mib)
			s.MemswapLimit = s.MemLimit // no swap on top
		}
	}
}

func healthy(names ...string) map[string]dependency {
	d := map[string]dependency{}
	for _, n := range names {
		d[n] = dependency{Condition: "service_healthy"}
	}
	return d
}

// header starts every generated file.
func header(bundleVersion string) string {
	return "# Generated by oaf (bundle " + bundleVersion + "). Do not edit: oaf apply overwrites this file.\n"
}

// marshalYAML renders v as 2-space YAML under the generated-file header.
func marshalYAML(bundleVersion string, v any) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header(bundleVersion))
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// envFile collects the secrets one project needs. Compose reads .env from the
// project directory for interpolation, so compose.yaml refers to secrets as
// ${NAME:?} and never contains a value.
type envFile struct {
	vars map[string]string
}

func newEnvFile() *envFile { return &envFile{vars: map[string]string{}} }

// ref records value under name and returns the compose interpolation for it.
func (e *envFile) ref(name, value string) string {
	e.vars[name] = value
	return "${" + name + ":?run oaf apply to regenerate .env}"
}

func (e *envFile) render(bundleVersion string) ([]byte, error) {
	var b strings.Builder
	b.WriteString(header(bundleVersion))
	b.WriteString("# Secrets for this project, from /etc/oaf/secrets. Mode 0600.\n")
	names := make([]string, 0, len(e.vars))
	for n := range e.vars {
		names = append(names, n)
	}
	slices.Sort(names)
	for _, n := range names {
		v := e.vars[n]
		// Values are generated hex/base64; reject anything that would need quoting.
		if strings.ContainsAny(v, " \t\r\n\"'$#\\`") {
			return nil, fmt.Errorf("secret for %s contains characters .env cannot hold unquoted", n)
		}
		fmt.Fprintf(&b, "%s=%s\n", n, v)
	}
	return []byte(b.String()), nil
}
