package join

import (
	"crypto/sha256"
	"crypto/x509"
	"encoding/base64"
	"encoding/pem"
	"errors"
	"fmt"
	"strings"
)

// PinFromCert is the curl --pinnedpubkey value (sha256//<base64 SPKI hash>)
// of a PEM certificate: oafd's TLS certificate, which join.sh pins instead
// of trusting whatever answers on the control node's address.
func PinFromCert(certPEM []byte) (string, error) {
	b, _ := pem.Decode(certPEM)
	if b == nil {
		return "", errors.New("no PEM certificate")
	}
	c, err := x509.ParseCertificate(b.Bytes)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(c.RawSubjectPublicKeyInfo)
	return "sha256//" + base64.StdEncoding.EncodeToString(sum[:]), nil
}

// Command is the one line an admin runs on a new box.
func Command(controlURL, pin, token string) string {
	return fmt.Sprintf("curl -fsSLk --pinnedpubkey '%s' %s/join.sh | sudo bash -s -- --token %s",
		pin, strings.TrimRight(controlURL, "/"), token)
}

// Script is join.sh, served by oafd at /join.sh. It holds no secret: the
// token comes on the command line. Every download pins oafd's TLS key, so
// it works with the cluster's own certificate and refuses an impostor. The
// oaf binary and the images come from the control node, so a box with no
// internet joins too. Nothing is deployed on join.
func Script(controlURL, pin string) string {
	r := strings.NewReplacer("@CONTROL@", strings.TrimRight(controlURL, "/"), "@PIN@", pin)
	return r.Replace(scriptTemplate)
}

const scriptTemplate = `#!/usr/bin/env bash
# Generated by oafd: joins this box to an openagentfabric cluster.
# Nothing is deployed on join; the admin chooses the topology afterwards.
set -euo pipefail

CONTROL="@CONTROL@"
PIN="@PIN@"
TOKEN=""
EXTRA=()
while [ $# -gt 0 ]; do
  case "$1" in
    --token) TOKEN="$2"; shift 2 ;;
    --skip-images) EXTRA+=(--skip-images); shift ;;
    --force) EXTRA+=(--force); shift ;;
    --name) EXTRA+=(--name "$2"); shift 2 ;;
    *) echo "join.sh: unknown argument $1" >&2; exit 2 ;;
  esac
done
[ -n "$TOKEN" ] || { echo "usage: join.sh --token <token> [--skip-images] [--name <node>] [--force]" >&2; exit 2; }
[ "$(id -u)" -eq 0 ] || { echo "join.sh: run as root (sudo)" >&2; exit 1; }
case "$(uname -m)" in
  aarch64) ARCH=arm64 ;;
  x86_64) ARCH=amd64 ;;
  *) echo "join.sh: unsupported architecture $(uname -m)" >&2; exit 1 ;;
esac
command -v docker >/dev/null || { echo "join.sh: docker is required (DGX OS ships it)" >&2; exit 1; }

echo "==> Downloading oaf ($ARCH) from $CONTROL"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
curl -fsSLk --pinnedpubkey "$PIN" -H "Authorization: Bearer $TOKEN" \
  -o "$tmp" "$CONTROL/api/v1/join/binary?arch=$ARCH"
install -m 0755 "$tmp" /usr/local/bin/oaf

echo "==> Joining"
exec /usr/local/bin/oaf join --control "$CONTROL" --pin "$PIN" --token "$TOKEN" "${EXTRA[@]}"
`
